package com.interviewplatform.backend.model;

public class SchoolEducation {
    private String board10th;
    private String school10th;
    private String year10th;
    private String percentage10th;
    private String board12th;
    private String school12th;
    private String year12th;
    private String percentage12th;

    public SchoolEducation() {}

    public String getBoard10th() { return board10th; }
    public void setBoard10th(String board10th) { this.board10th = board10th; }

    public String getSchool10th() { return school10th; }
    public void setSchool10th(String school10th) { this.school10th = school10th; }

    public String getYear10th() { return year10th; }
    public void setYear10th(String year10th) { this.year10th = year10th; }

    public String getPercentage10th() { return percentage10th; }
    public void setPercentage10th(String percentage10th) { this.percentage10th = percentage10th; }

    public String getBoard12th() { return board12th; }
    public void setBoard12th(String board12th) { this.board12th = board12th; }

    public String getSchool12th() { return school12th; }
    public void setSchool12th(String school12th) { this.school12th = school12th; }

    public String getYear12th() { return year12th; }
    public void setYear12th(String year12th) { this.year12th = year12th; }

    public String getPercentage12th() { return percentage12th; }
    public void setPercentage12th(String percentage12th) { this.percentage12th = percentage12th; }
}
